with st.form(key="bdi_form"):
    col1, col2 = st.columns(2)
    with col1:
        subject_code = st.text_input("کد / شناسه آزمودنی:")
    with col2:
        full_name = st.text_input("نام و نام خانوادگی:")
        
    st.write("---")
    
    responses = {}
    for q in questions:
        st.markdown(f"### {q['title']}")
        options_text = [opt[0] for opt in q["options"]]
        
        selected_option = st.radio(
            label="لطفاً یک مورد را انتخاب کنید:",
            options=options_text,
            key=f"q_{q['id']}",
            index=None
        )
        
        score = 0
        if selected_option:
            for text, sc in q["options"]:
                if text == selected_option:
                    score = sc
                    break
                    
        responses[f"Q{q['id']}"] = score
        st.write("")

    submitted = st.form_submit_button("ثبت و دریافت نتیجه", use_container_width=True)

if submitted:
    if not subject_code.strip() or not full_name.strip():
        st.error("لطفاً هم «کد / شناسه آزمودنی» و هم «نام و نام خانوادگی» را وارد کنید.")
    elif None in [st.session_state.get(f"q_{q['id']}") for q in questions]:
        st.warning("لطفاً به تمامی ۲۱ سوال پاسخ دهید.")
    else:
        total_score = sum(responses.values())
        
        if total_score <= 13:
            severity = "طبیعی (افسردگی ندارد)"
            color = "green"
        elif total_score <= 19:
            severity = "افسردگی خفیف"
            color = "orange"
        elif total_score <= 28:
            severity = "افسردگی متوسط"
            color = "red"
        else:
            severity = "افسردگی شدید"
            color = "darkred"
            
        st.success("پاسخ‌های شما با موفقیت ثبت شد!")
        st.markdown(f"### نمره کل: **{total_score}** از ۶۳")
        st.markdown(f"### تفسیر وضعیت: **:{color}[{severity}]**")
        
        record = {
            "Timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "Subject_ID": subject_code.strip(),
            "Full_Name": full_name.strip(),
            "Total_Score": total_score,
            "Severity": severity
        }
        record.update(responses)
        save_bdi_gsheet(record)
        st.info("پاسخ‌ها با موفقیت در گوگل شیت ذخیره گردید.")