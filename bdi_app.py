def save_bdi_gsheet(data_dict):
    try:
        existing_data = conn.read(worksheet="BDI_Data", ttl=0)
        updated_df = pd.concat([existing_data, pd.DataFrame([data_dict])], ignore_index=True)
        conn.update(worksheet="BDI_Data", data=updated_df)
    except Exception:
        df_new = pd.DataFrame([data_dict])
        conn.update(worksheet="BDI_Data", data=df_new)

